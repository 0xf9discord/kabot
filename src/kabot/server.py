"""FastAPI skill server with bounded requests, deadlines and optional callbacks."""

from __future__ import annotations

import asyncio
import hmac
import json
import logging
import re
from urllib.parse import urlsplit

import httpx
from fastapi import BackgroundTasks, FastAPI, HTTPException, Request
from pydantic import ValidationError

from .bot import Bot, Context, Route
from .models import SkillRequest, text

logger = logging.getLogger("kabot.server")


def callback_allowed(url: str, hosts: frozenset[str]) -> bool:
    try:
        parsed = urlsplit(url)
        return (
            parsed.scheme == "https"
            and parsed.hostname in hosts
            and parsed.port in (None, 443)
            and parsed.username is None
            and parsed.password is None
            and not parsed.fragment
        )
    except ValueError:
        return False


def create_app(
    bot: Bot,
    *,
    webhook_secret: str,
    expected_bot_id: str | None = None,
    timeout: float = 4.0,
    max_body_bytes: int = 262144,
    callback_hosts: tuple[str, ...] = (),
    callback_timeout: float = 40.0,
    callback_client: httpx.AsyncClient | None = None,
) -> FastAPI:
    """Set the skill URL to /skill/<secret>. Secrets are generated by the operator.

    Callback hostnames must be exact, operator-verified Kakao hosts. No outbound
    callback is enabled by default. Background tasks are process-local, not a durable queue.
    """
    if not re.fullmatch(r"[A-Za-z0-9_-]{24,128}", webhook_secret):
        raise ValueError("webhook_secret must be 24..128 URL-safe characters")
    if not 0 < timeout < 5 or not 0 < callback_timeout <= 45 or max_body_bytes < 1:
        raise ValueError("Require 0<timeout<5, 0<callback_timeout<=45, positive body limit")
    hosts = frozenset(h.lower() for h in callback_hosts)
    if any(not re.fullmatch(r"[a-z0-9][a-z0-9.-]*[a-z0-9]", h) for h in hosts):
        raise ValueError("callback_hosts must contain exact DNS hostnames")
    app = FastAPI(title="Kabot skill server", docs_url=None, redoc_url=None, openapi_url=None)

    async def deferred(route: Route, ctx: Context, url: str) -> None:
        try:
            response = await asyncio.wait_for(bot.execute(route, ctx), callback_timeout)
        except Exception as exc:
            # Neither URLs nor payloads/tokens are logged. Worker failures are visible.
            logger.error("Deferred handler failed (%s)", type(exc).__name__)
            response = text("처리 중 오류가 발생했습니다. 잠시 후 다시 시도해 주세요.")
        try:

            async def post(client: httpx.AsyncClient):
                result = await client.post(
                    url, json=response.to_dict(), timeout=5, follow_redirects=False
                )
                result.raise_for_status()
                body = result.json()
                if body.get("status") != "SUCCESS":
                    raise ValueError("Kakao callback did not return SUCCESS")

            if callback_client is not None:
                await post(callback_client)
            else:
                async with httpx.AsyncClient(trust_env=False) as client:
                    await post(client)
        except Exception as exc:
            # A callback token is single-use. Never retry an ambiguous POST.
            logger.error("Callback delivery failed (%s); no retry attempted", type(exc).__name__)

    @app.get("/healthz")
    async def health():
        return {"status": "ok", "transport": "kakao-channel-skill"}

    @app.post("/skill/{secret}")
    async def skill(secret: str, request: Request, background_tasks: BackgroundTasks):
        if not hmac.compare_digest(secret.encode(), webhook_secret.encode()):
            raise HTTPException(404, "Not found")
        body = bytearray()
        async for chunk in request.stream():
            body.extend(chunk)
            if len(body) > max_body_bytes:
                raise HTTPException(413, "Payload too large")
        try:
            payload = SkillRequest.model_validate(json.loads(body))
        except (ValidationError, ValueError, UnicodeDecodeError):
            raise HTTPException(400, "Invalid skill payload") from None
        if expected_bot_id is not None and payload.bot.get("id") != expected_bot_id:
            raise HTTPException(403, "Unexpected bot")
        route, ctx = bot.resolve(payload)
        if route is not None and route.deferred:
            url = payload.user_request.callback_url
            if not url or not callback_allowed(url, hosts):
                return text(
                    "이 기능은 서버의 콜백 설정과 카카오 블록의 콜백 활성화가 필요합니다."
                ).to_dict()
            background_tasks.add_task(deferred, route, ctx, url)
            return {"version": "2.0", "useCallback": True}
        try:
            response = await asyncio.wait_for(bot.execute(route, ctx), timeout)
            return response.to_dict()
        except TimeoutError:
            logger.warning("Skill handler exceeded response deadline")
            return text("처리 시간이 초과되었습니다. 잠시 후 다시 시도해 주세요.").to_dict()
        except Exception as exc:
            logger.error("Skill handler failed (%s)", type(exc).__name__)
            return text("처리 중 오류가 발생했습니다. 잠시 후 다시 시도해 주세요.").to_dict()

    return app
